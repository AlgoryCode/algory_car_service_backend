package com.algorycarservice.common.exception;

import lombok.Getter;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;

/** Stable, client-facing error codes. Their texts live in {@code messages.properties} under {@code error.<CODE>}. */
@Getter
@RequiredArgsConstructor
public enum ErrorCode {

    VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
    MALFORMED_REQUEST(HttpStatus.BAD_REQUEST),
    INVALID_CREDENTIALS(HttpStatus.UNAUTHORIZED),
    INVALID_REFRESH_TOKEN(HttpStatus.UNAUTHORIZED),
    AUTHENTICATION_REQUIRED(HttpStatus.UNAUTHORIZED),
    ACCESS_DENIED(HttpStatus.FORBIDDEN),
    RESOURCE_NOT_FOUND(HttpStatus.NOT_FOUND),
    METHOD_NOT_ALLOWED(HttpStatus.METHOD_NOT_ALLOWED),
    REGISTRATION_CLOSED(HttpStatus.CONFLICT),
    EMAIL_ALREADY_REGISTERED(HttpStatus.CONFLICT),
    PLATE_ALREADY_REGISTERED(HttpStatus.CONFLICT),
    PASSWORD_MISMATCH(HttpStatus.UNPROCESSABLE_CONTENT),
    CANNOT_CHANGE_OWN_ACCOUNT(HttpStatus.UNPROCESSABLE_CONTENT),
    INVALID_DATE_RANGE(HttpStatus.UNPROCESSABLE_CONTENT),
    LEAVE_OVERLAPS(HttpStatus.CONFLICT),
    LEAVE_BALANCE_EXCEEDED(HttpStatus.UNPROCESSABLE_CONTENT),
    LEAVE_ALREADY_REVIEWED(HttpStatus.CONFLICT),
    WORK_ORDER_ALREADY_PAID(HttpStatus.CONFLICT),
    WORK_ORDER_NOT_PAID(HttpStatus.CONFLICT),
    LINKED_TRANSACTION(HttpStatus.CONFLICT),
    WORK_ORDER_OTHER_VEHICLE(HttpStatus.UNPROCESSABLE_CONTENT),
    APPOINTMENT_CLOSED_DAY(HttpStatus.UNPROCESSABLE_CONTENT),
    APPOINTMENT_INVALID_TIME(HttpStatus.UNPROCESSABLE_CONTENT),
    APPOINTMENT_IN_PAST(HttpStatus.UNPROCESSABLE_CONTENT),
    APPOINTMENT_SLOT_FULL(HttpStatus.CONFLICT),
    APPOINTMENT_DUPLICATE(HttpStatus.CONFLICT),
    APPOINTMENT_STATUS_INVALID(HttpStatus.CONFLICT),
    APPOINTMENT_VEHICLE_REQUIRED(HttpStatus.UNPROCESSABLE_CONTENT),
    SERVICE_NOT_OFFERED(HttpStatus.UNPROCESSABLE_CONTENT),
    STAFF_ROLE_INVALID(HttpStatus.UNPROCESSABLE_CONTENT),
    PHOTO_INVALID(HttpStatus.UNPROCESSABLE_CONTENT),
    PHOTO_TOO_LARGE(HttpStatus.CONTENT_TOO_LARGE),
    PHOTO_LIMIT_REACHED(HttpStatus.CONFLICT),
    STORAGE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);

    private final HttpStatus status;

    public String messageKey() {
        return "error." + name();
    }
}
