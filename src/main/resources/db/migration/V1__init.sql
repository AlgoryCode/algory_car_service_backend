CREATE TABLE users
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(160)             NOT NULL,
    password_hash     VARCHAR(100)             NOT NULL,
    full_name         VARCHAR(100)             NOT NULL,
    phone             VARCHAR(20),
    position          VARCHAR(60),
    role              VARCHAR(10)              NOT NULL,
    annual_leave_days INTEGER                  NOT NULL,
    active            BOOLEAN                  NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE refresh_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64)              NOT NULL,
    session_id VARCHAR(36)              NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash)
);

CREATE TABLE vehicles
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate       VARCHAR(16)              NOT NULL,
    brand       VARCHAR(60)              NOT NULL,
    model       VARCHAR(60)              NOT NULL,
    model_year  INTEGER,
    color       VARCHAR(30),
    vin         VARCHAR(17),
    owner_name  VARCHAR(100)             NOT NULL,
    owner_phone VARCHAR(20),
    notes       VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_vehicles_plate UNIQUE (plate)
);

CREATE TABLE work_orders
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    BIGINT                   NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    status        VARCHAR(20)              NOT NULL,
    complaint     VARCHAR(500)             NOT NULL,
    notes         VARCHAR(1000),
    mileage_km    INTEGER,
    technician_id BIGINT REFERENCES users (id),
    opened_on     DATE                     NOT NULL,
    completed_on  DATE,
    paid_on       DATE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_work_orders_vehicle ON work_orders (vehicle_id, opened_on DESC);
CREATE INDEX idx_work_orders_status ON work_orders (status);

CREATE TABLE work_order_items
(
    work_order_id BIGINT         NOT NULL REFERENCES work_orders (id) ON DELETE CASCADE,
    line_no       INTEGER        NOT NULL,
    kind          VARCHAR(10)    NOT NULL,
    description   VARCHAR(150)   NOT NULL,
    quantity      NUMERIC(8, 2)  NOT NULL,
    unit_price    NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (work_order_id, line_no)
);

CREATE TABLE finance_transactions
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(10)              NOT NULL,
    category         VARCHAR(20)              NOT NULL,
    amount           NUMERIC(12, 2)           NOT NULL,
    transaction_date DATE                     NOT NULL,
    description      VARCHAR(200),
    work_order_id    BIGINT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_finance_transactions_work_order UNIQUE (work_order_id)
);

CREATE INDEX idx_finance_transactions_date ON finance_transactions (transaction_date DESC);

CREATE TABLE leave_requests
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type        VARCHAR(10)              NOT NULL,
    start_date  DATE                     NOT NULL,
    end_date    DATE                     NOT NULL,
    days        INTEGER                  NOT NULL,
    reason      VARCHAR(300),
    status      VARCHAR(10)              NOT NULL,
    reviewer_id BIGINT REFERENCES users (id),
    review_note VARCHAR(300),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_leave_requests_dates ON leave_requests (start_date, end_date);
CREATE INDEX idx_leave_requests_user ON leave_requests (user_id, start_date DESC);
