-- Booked visits (mainly vehicle inspections). A request may come for a car that is not registered yet, so the plate
-- and the customer are kept on the appointment and the vehicle link is optional.
CREATE TABLE appointments
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id       BIGINT REFERENCES vehicles (id) ON DELETE SET NULL,
    plate            VARCHAR(16)              NOT NULL,
    customer_name    VARCHAR(100)             NOT NULL,
    customer_phone   VARCHAR(20),
    type             VARCHAR(20)              NOT NULL,
    appointment_date DATE                     NOT NULL,
    start_time       TIME                     NOT NULL,
    status           VARCHAR(12)              NOT NULL,
    notes            VARCHAR(500),
    status_note      VARCHAR(300),
    created_by_id    BIGINT REFERENCES users (id),
    work_order_id    BIGINT REFERENCES work_orders (id) ON DELETE SET NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_appointments_slot ON appointments (appointment_date, start_time);
CREATE INDEX idx_appointments_plate ON appointments (plate, appointment_date);
