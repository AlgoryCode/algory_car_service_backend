-- Points marked on the vehicle drawing (a scratch, a dent...) with optional photos kept in SeaweedFS.
CREATE TABLE vehicle_marks
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    BIGINT                   NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    work_order_id BIGINT REFERENCES work_orders (id) ON DELETE SET NULL,
    car_view      VARCHAR(10)              NOT NULL,
    pos_x         DOUBLE PRECISION         NOT NULL,
    pos_y         DOUBLE PRECISION         NOT NULL,
    type          VARCHAR(15)              NOT NULL,
    part          VARCHAR(30),
    note          VARCHAR(300),
    created_by    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_vehicle_marks_vehicle ON vehicle_marks (vehicle_id);

CREATE TABLE vehicle_mark_photos
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mark_id      BIGINT                   NOT NULL REFERENCES vehicle_marks (id) ON DELETE CASCADE,
    object_key   VARCHAR(200)             NOT NULL,
    content_type VARCHAR(30)              NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_vehicle_mark_photos_mark ON vehicle_mark_photos (mark_id);
